import React from "react";
import hinglishTimeline from "./data/github-tricks.json";
import englishTimeline from "./data/github-tricks-en.json";
import fahimTimeline from "./data/github-tricks-en-fahim.json";
import { Explainer, ExplainerConfig } from "./Explainer";
import { CtaScene } from "./scenes/Cta";
import { DiagramScene } from "./scenes/Diagram";
import { HookScene, ReverseScene } from "./scenes/GitReverse";
import { RecapScene, TeaserScene } from "./scenes/Lists";
import { WikiScene } from "./scenes/Wiki";
import type { Timeline } from "./timeline";

const BRAND = "Fahim Khan";

/**
 * "5 GitHub URL tricks" reel. Scenes are language-neutral: they animate on `#tag`
 * cues and read on-screen text from the job's `copy`, so each language is just a
 * timeline generated by tts/build_voiceover.py from jobs/<id>.json.
 */
const makeGithubTricks = (id: string, timeline: Timeline, voiceSrc: string): ExplainerConfig => ({
  id,
  brand: BRAND,
  voiceSrc,
  timeline,
  labels: {
    hook: "1 WORD",
    reverse: "TRICK 1/5",
    teaser: "NEXT",
    diagram: "TRICK 2/5",
    wiki: "TRICK 3/5",
    recap: "5 TRICKS",
    cta: "COMMENT GITHUB",
  },
  scenes: {
    hook: (s) => <HookScene scene={s} />,
    reverse: (s) => <ReverseScene scene={s} />,
    teaser: (s) => <TeaserScene scene={s} />,
    diagram: (s) => <DiagramScene scene={s} />,
    wiki: (s) => <WikiScene scene={s} />,
    recap: (s) => <RecapScene scene={s} />,
    cta: (s) => <CtaScene scene={s} brand={BRAND} />,
  },
});

export const GITHUB_TRICKS = makeGithubTricks("GithubTricks", hinglishTimeline as Timeline, "github-tricks/voice.wav");
export const GITHUB_TRICKS_EN = makeGithubTricks("GithubTricksEn", englishTimeline as Timeline, "github-tricks-en/voice.wav");
/** English script narrated by the "Fahim Khan" ElevenLabs voice clone (jobs/github-tricks-en-fahim.json). */
export const GITHUB_TRICKS_EN_FAHIM = makeGithubTricks(
  "GithubTricksEnFahim",
  fahimTimeline as Timeline,
  "github-tricks-en-fahim/voice.wav",
);

/** Composition entries: configs hold render functions, so they can't travel through defaultProps. */
export const GithubTricksReel: React.FC = () => <Explainer config={GITHUB_TRICKS} />;
export const GithubTricksEnReel: React.FC = () => <Explainer config={GITHUB_TRICKS_EN} />;
export const GithubTricksEnFahimReel: React.FC = () => <Explainer config={GITHUB_TRICKS_EN_FAHIM} />;
